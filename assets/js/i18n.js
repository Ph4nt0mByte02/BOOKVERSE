let currentLanguage = Storage.get("language", "es");

export function getLanguage() {
  return currentLanguage;
}

export function t(key) {
  const langDict = translations[currentLanguage] || translations.es;
  return langDict[key] || translations.es[key] || key;
}

export function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLanguage = lang;
  Storage.set("language", lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = "ltr";

  // Translate all DOM elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    const translation = t(key);
    if (translation) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = translation;
      } else {
        el.textContent = translation;
      }
    }
  });

  // Translate placeholders with data-i18n-placeholder
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    const translation = t(key);
    if (translation) {
      el.placeholder = translation;
    }
  });

  // Update language select dropdowns if any
  document.querySelectorAll(".lang-select, #lang-selector").forEach((sel) => {
    if (sel.value !== lang) sel.value = lang;
  });

  document.dispatchEvent(new CustomEvent("bookverse:language-changed", { detail: lang }));
}

// Initialize on script load
export function initI18n() {
  setLanguage(currentLanguage);
}
